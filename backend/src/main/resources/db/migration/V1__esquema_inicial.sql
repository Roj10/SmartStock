-- V1: esquema inicial do SmartStock (estoque, movimentações, fornecedores, projetos/produção, anexos,
-- modelos de projeto, financeiro, mensagens e usuários com permissões por aba).
-- As tabelas ficam no schema configurado em spring.flyway.default-schema (smartstock).
-- Bancos que já existiam antes das migrations (criados pelo Hibernate) são marcados como V1 sem executar este
-- arquivo (spring.flyway.baseline-on-migrate=true).

create table checklist_itens (
    concluido boolean not null,
    ordem integer not null,
    id bigint generated by default as identity,
    projeto_id bigint not null,
    texto varchar(255) not null,
    primary key (id)
);

create table fornecedor_produtos (
    preco numeric(12,2) not null,
    fornecedor_id bigint not null,
    id bigint generated by default as identity,
    pastilha_id bigint not null,
    primary key (id),
    unique (fornecedor_id, pastilha_id)
);

create table fornecedores (
    id bigint generated by default as identity,
    contato varchar(255),
    email varchar(255),
    nome varchar(255) not null,
    telefone varchar(255),
    tipo varchar(255) not null check (tipo in ('FABRICANTE','FORNECEDOR','AMBOS')),
    primary key (id)
);

create table mensagens (
    lida boolean not null,
    data_hora timestamp(6) not null,
    destinatario_id bigint not null,
    id bigint generated by default as identity,
    remetente_id bigint not null,
    texto varchar(2000) not null,
    imagem_arquivo varchar(255),
    imagem_tipo varchar(255),
    primary key (id)
);

create table modelo_projeto_etapas (
    ordem integer not null,
    modelo_id bigint not null,
    texto varchar(255) not null,
    primary key (ordem, modelo_id)
);

create table modelo_projeto_materiais (
    ordem integer not null,
    quantidade integer not null,
    modelo_id bigint not null,
    pastilha_id bigint not null,
    primary key (ordem, modelo_id)
);

create table modelos_projeto (
    data_criacao timestamp(6) not null,
    id bigint generated by default as identity,
    descricao varchar(255),
    nome varchar(255) not null,
    primary key (id)
);

create table movimentacoes (
    quantidade integer not null,
    data_hora timestamp(6) not null,
    fornecedor_id bigint,
    id bigint generated by default as identity,
    pastilha_id bigint not null,
    usuario_id bigint,
    observacao varchar(255),
    tipo varchar(255) not null check (tipo in ('ENTRADA','SAIDA')),
    primary key (id)
);

create table pastilhas (
    estoque_minimo integer not null,
    quantidade_atual integer not null,
    fabricante_id bigint,
    id bigint generated by default as identity,
    codigo varchar(255) not null unique,
    descricao varchar(255) not null,
    imagem_url varchar(255),
    primary key (id)
);

create table projeto_anexos (
    data_envio timestamp(6) not null,
    id bigint generated by default as identity,
    projeto_id bigint not null,
    tamanho bigint not null,
    arquivo varchar(255) not null,
    nome_original varchar(255) not null,
    tipo varchar(255) not null,
    primary key (id)
);

create table projeto_materiais (
    quantidade integer not null,
    id bigint generated by default as identity,
    pastilha_id bigint not null,
    projeto_id bigint not null,
    primary key (id)
);

create table projetos (
    data_pedido date,
    meta_entrega date,
    data_criacao timestamp(6) not null,
    data_entrega timestamp(6),
    data_finalizacao_producao timestamp(6),
    data_inicio_producao timestamp(6),
    id bigint generated by default as identity,
    cliente varchar(255),
    descricao varchar(255),
    nome varchar(255) not null,
    status varchar(255) not null check (status in ('AGUARDANDO','EM_PRODUCAO','EM_ESTOQUE','PRONTO_ENTREGA','PEDIDO_ENVIADO','ENTREGUE')),
    primary key (id)
);

create table usuario_permissoes (
    usuario_id bigint not null,
    modulo varchar(255) not null check (modulo in ('PASTILHAS','MOVIMENTACOES','FORNECEDORES','USUARIOS','PROJETOS','FINANCEIRO')),
    primary key (usuario_id, modulo)
);

create table usuarios (
    id bigint generated by default as identity,
    nome varchar(255) not null,
    role varchar(255) not null check (role in ('ADMIN','OPERADOR')),
    senha varchar(255) not null,
    username varchar(255) not null unique,
    primary key (id)
);

create table vendas (
    data_criacao date not null,
    data_venda date,
    valor numeric(12,2) not null,
    id bigint generated by default as identity,
    projeto_id bigint,
    cliente varchar(255) not null,
    descricao varchar(255),
    status varchar(255) not null check (status in ('PLANO','VENDA')),
    primary key (id)
);

