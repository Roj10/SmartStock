-- V2: segurança - autenticação em dois fatores (app autenticador), códigos de recuperação, versão do login
-- (para encerrar sessões), troca obrigatória de senha e registro de eventos de segurança.
-- Escrita para rodar também em bancos onde essas colunas/tabelas já existem (IF NOT EXISTS).

alter table usuarios add column if not exists dois_fatores_ativo boolean default false not null;
alter table usuarios add column if not exists token_versao integer default 0 not null;
alter table usuarios add column if not exists trocar_senha boolean default false not null;
alter table usuarios add column if not exists totp_ultimo_passo bigint default 0 not null;
alter table usuarios add column if not exists totp_pendente varchar(200);
alter table usuarios add column if not exists totp_segredo varchar(200);

create table if not exists eventos_seguranca (
    data_hora timestamp(6) not null,
    id bigint generated by default as identity,
    tipo varchar(40) not null,
    ip varchar(64),
    usuario varchar(100),
    detalhe varchar(300),
    primary key (id)
);

create index if not exists idx_evento_data on eventos_seguranca (data_hora);

create table if not exists usuario_codigos_recuperacao (
    usuario_id bigint not null,
    codigo_hash varchar(255) not null,
    primary key (usuario_id, codigo_hash),
    constraint fk_codigos_recuperacao_usuario foreign key (usuario_id) references usuarios (id)
);
